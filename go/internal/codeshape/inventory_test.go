func newFixtureRepo(t *testing.T) string {
	t.Helper()
	root := t.TempDir()
	command := exec.Command("git", "init", "-q")
	command.Dir = root
	if output, err := command.CombinedOutput(); err != nil {
		t.Fatalf("git init: %v: %s", err, output)
	}
	command = exec.Command("git", "-C", root, "config", "user.email", "test@example.invalid")
	if output, err := command.CombinedOutput(); err != nil {
		t.Fatalf("git config: %v: %s", err, output)
	}
	command = exec.Command("git", "-C", root, "config", "user.name", "test")
	if output, err := command.CombinedOutput(); err != nil {
		t.Fatalf("git config: %v: %s", err, output)
	}
	return root
}

func trackedFile(t *testing.T, root, path, content string) {
	t.Helper()
	fullPath := filepath.Join(root, filepath.FromSlash(path))
	if err := os.MkdirAll(filepath.Dir(fullPath), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(fullPath, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

func commitFiles(t *testing.T, root string) {
	t.Helper()
	command := exec.Command("git", "-C", root, "add", "--all")
	if output, err := command.CombinedOutput(); err != nil {
		t.Fatalf("git add: %v: %s", err, output)
	}
	command = exec.Command("git", "-C", root, "commit", "-qm", "fixture")
	if output, err := command.CombinedOutput(); err != nil {
		t.Fatalf("git commit: %v: %s", err, output)
	}
}

func TestInventory(t *testing.T) {
	t.Run("file one line over limit is measured", func(t *testing.T) {
		root := newFixtureRepo(t)
		trackedFile(t, root, "large.go", strings.Repeat("line\n", 501))
		commitFiles(t, root)
		snapshot, err := Inventory(context.Background(), root, testConfig())
		if err != nil {
			t.Fatal(err)
		}
		if snapshot.Files["large.go"] != 501 {
			t.Fatalf("file lines = %d, want 501", snapshot.Files["large.go"])
		}
		findings := Judge(testConfig(), Allowlist{}, Allowlist{}, snapshot)
		if !hasFinding(findings, "large.go", MetricFiles, 501, 500, "split this file") {
			t.Fatalf("missing one-over finding: %#v", findings)
		}
	})
	t.Run("testdata files skip file length", func(t *testing.T) {
		root := newFixtureRepo(t)
		trackedFile(t, root, "pkg/testdata/large.go", strings.Repeat("line\n", 501))
		commitFiles(t, root)
		snapshot, err := Inventory(context.Background(), root, testConfig())
		if err != nil {
			t.Fatal(err)
		}
		if _, exists := snapshot.Files["pkg/testdata/large.go"]; exists {
			t.Fatal("testdata file counted toward file length")
		}
		if snapshot.Dirs["pkg/testdata"] != 1 {
			t.Fatalf("testdata direct files = %d, want 1", snapshot.Dirs["pkg/testdata"])
		}
	})
	t.Run("fixtures files skip file length", func(t *testing.T) {
		root := newFixtureRepo(t)
		trackedFile(t, root, "pkg/fixtures/large.go", strings.Repeat("line\n", 501))
		commitFiles(t, root)
		snapshot, err := Inventory(context.Background(), root, testConfig())
		if err != nil {
			t.Fatal(err)
		}
		if _, exists := snapshot.Files["pkg/fixtures/large.go"]; exists {
			t.Fatal("fixtures file counted toward file length")
		}
	})
}

func TestInventoryGeneratedAndExcluded(t *testing.T) {
	t.Run("generated header in first five lines skips file length", func(t *testing.T) {
		root := newFixtureRepo(t)
		trackedFile(t, root, "generated.go", "// Code generated by tool. DO NOT EDIT.\n"+strings.Repeat("line\n", 501))
		commitFiles(t, root)
		snapshot, err := Inventory(context.Background(), root, testConfig())
		if err != nil {
			t.Fatal(err)
		}
		if _, exists := snapshot.Files["generated.go"]; exists {
			t.Fatal("generated file counted toward file length")
		}
	})
	t.Run("at generated marker skips file length", func(t *testing.T) {
		lines, generated, err := physicalLines(strings.NewReader("one\ntwo\nthree\nfour\n// @generated\nsix\n"))
		if err != nil || !generated || lines != 6 {
			t.Fatalf("lines=%d generated=%v error=%v", lines, generated, err)
		}
	})
	t.Run("generated marker after fifth line is counted", func(t *testing.T) {
		_, generated, err := physicalLines(strings.NewReader("one\ntwo\nthree\nfour\nfive\n// @generated\n"))
		if err != nil || generated {
			t.Fatalf("generated=%v error=%v", generated, err)
		}
	})
	t.Run("exclude glob skips file length only", func(t *testing.T) {
		root := newFixtureRepo(t)
		trackedFile(t, root, "pkg/large.go", strings.Repeat("line\n", 501))
		commitFiles(t, root)
		config := testConfig()
		config.Exclude = []string{"pkg/**"}
		snapshot, err := Inventory(context.Background(), root, config)
		if err != nil {
			t.Fatal(err)
		}
		if _, exists := snapshot.Files["pkg/large.go"]; exists || snapshot.Dirs["pkg"] != 1 {
			t.Fatalf("exclude applied incorrectly: %#v", snapshot)
		}
	})
}

func TestInventoryDirectoryWidth(t *testing.T) {
	t.Run("directory width counts all tracked file types at eleven", func(t *testing.T) {
		root := newFixtureRepo(t)
		for index := range 11 {
			trackedFile(t, root, fmt.Sprintf("wide/file-%02d.txt", index), "text\n")
		}
		commitFiles(t, root)
		snapshot, err := Inventory(context.Background(), root, testConfig())
		if err != nil {
			t.Fatal(err)
		}
		if snapshot.Dirs["wide"] != 11 {
			t.Fatalf("directory files = %d, want 11", snapshot.Dirs["wide"])
		}
		findings := Judge(testConfig(), Allowlist{}, Allowlist{}, snapshot)
		if !hasFinding(findings, "wide", MetricDirs, 11, 10, "split the directory") {
			t.Fatalf("missing 11-file directory finding: %#v", findings)
		}
	})
	t.Run("directory width ten passes", func(t *testing.T) {
		root := newFixtureRepo(t)
		for index := range 10 {
			trackedFile(t, root, fmt.Sprintf("wide/file-%02d.txt", index), "text\n")
		}
		commitFiles(t, root)
		snapshot, err := Inventory(context.Background(), root, testConfig())
		if err != nil {
			t.Fatal(err)
		}
		if findings := Judge(testConfig(), Allowlist{}, Allowlist{}, snapshot); len(findings) != 0 {
			t.Fatalf("10-file directory findings = %#v", findings)
		}
	})
}

func testConfig() Config {
	return Config{FileLimit: 500, DirLimit: 10, Extensions: []string{".go", ".cue"}}
}
