package inventory_test

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/RigelBuild/meissa/go/internal/codeshape/inventory"
	"github.com/RigelBuild/meissa/go/internal/codeshape/judge"
	"github.com/RigelBuild/meissa/go/internal/codeshape/model"
	"github.com/RigelBuild/meissa/go/internal/codeshape/testsupport"
)

func TestInventory(t *testing.T) {
	root := testsupport.NewFixtureRepo(t)
	testsupport.TrackedFile(t, root, "large.go", strings.Repeat("line\n", 501))
	testsupport.TrackedFile(t, root, "generated.go", "// Code generated by tool. DO NOT EDIT.\nsource\n")
	testsupport.CommitFiles(t, root)
	paths, err := inventory.TrackedPaths(t.Context(), root)
	if err != nil {
		t.Fatal(err)
	}
	repository, err := os.OpenRoot(root)
	if err != nil {
		t.Fatal(err)
	}
	defer repository.Close()
	snapshot, err := inventory.Inventory(paths, testsupport.Config(), repository)
	if err != nil {
		t.Fatal(err)
	}
	if snapshot.Files["large.go"] != 501 {
		t.Fatalf("files = %#v", snapshot.Files)
	}
	if _, exists := snapshot.Files["generated.go"]; exists {
		t.Fatalf("generated source counted: %#v", snapshot.Files)
	}
	findings := judge.Judge(testsupport.Config(), model.Allowlist{}, model.Allowlist{}, snapshot)
	if len(findings) != 1 || findings[0].Metric != model.MetricFiles {
		t.Fatalf("findings = %#v", findings)
	}
}

func TestInventoryRejectsSymlinkEscape(t *testing.T) {
	root := testsupport.NewFixtureRepo(t)
	outside := filepath.Join(t.TempDir(), "outside.go")
	if err := os.WriteFile(outside, []byte(strings.Repeat("line\n", 600)), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(outside, filepath.Join(root, "escape.go")); err != nil {
		t.Fatal(err)
	}
	paths := []string{"escape.go"}
	repository, err := os.OpenRoot(root)
	if err != nil {
		t.Fatal(err)
	}
	defer repository.Close()
	if _, err := inventory.Inventory(paths, testsupport.Config(), repository); err == nil {
		t.Fatal("inventory followed a source symlink outside repository")
	}
}
